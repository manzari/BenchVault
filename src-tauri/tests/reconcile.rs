//! Regression test for the gcode-discovery gap: a slicer saves gcode into an
//! existing object's folder while the app (and its watcher) isn't running, so no
//! filesystem event is ever seen. `jobs::watcher::reconcile` must pick it up.

use std::sync::Arc;

use benchvault_lib::domain::AssetKind;
use benchvault_lib::jobs::watcher;
use benchvault_lib::library::Library;
use benchvault_lib::{db, repository};

async fn setup() -> (tempfile::TempDir, sqlx::SqlitePool, Arc<Library>) {
    let tmp = tempfile::tempdir().unwrap();
    let app_data = tmp.path().to_path_buf();
    let library = Arc::new(Library::new(app_data.clone()));
    library.ensure_dirs().unwrap();
    let pool = db::init_pool(&app_data.join("benchvault.db")).await.unwrap();
    db::run_migrations(&pool).await.unwrap();
    (tmp, pool, library)
}

const SAMPLE_GCODE: &str = "; generated by OrcaSlicer 2.1.0\n\
; estimated printing time (normal mode) = 1h 39m 12s\n\
; filament used [mm] = 4200.5\n\
; filament used [g] = 12.7\n\
G1 X0 Y0\n";

#[tokio::test]
async fn reconcile_discovers_gcode_dropped_into_existing_object_dir() {
    let (_tmp, pool, library) = setup().await;

    // Mirror the real data: folder "Plants" → object "Moss Pole Continuous holes".
    let folder = repository::folders::create(&pool, None, "Plants", "Plants")
        .await
        .unwrap();
    let _object = repository::objects::create(
        &pool,
        Some(folder.id),
        "Moss Pole Continuous holes",
        "Moss Pole Continuous holes",
    )
    .await
    .unwrap();

    // Slicer writes gcode straight into the object's on-disk dir — no app event.
    let obj_dir = library
        .root()
        .join("Plants")
        .join("Moss Pole Continuous holes");
    std::fs::create_dir_all(&obj_dir).unwrap();
    let gcode_path = obj_dir.join("moss_pole_long_PLA_0.2_2h13m.gcode");
    std::fs::write(&gcode_path, SAMPLE_GCODE).unwrap();

    // Nothing tracked yet.
    let rel = "Plants/Moss Pole Continuous holes/moss_pole_long_PLA_0.2_2h13m.gcode";
    assert!(repository::assets::find_by_relative_path(&pool, rel)
        .await
        .unwrap()
        .is_none());

    // The fix.
    let n = watcher::reconcile(&pool, &library).await.unwrap();
    assert_eq!(n, 1, "exactly one untracked file should be ingested");

    // Now tracked as a gcode asset attached to the object, with parsed metadata.
    let asset = repository::assets::find_by_relative_path(&pool, rel)
        .await
        .unwrap()
        .expect("gcode should be tracked after reconcile");
    assert!(matches!(asset.kind, AssetKind::Gcode));

    let meta = repository::gcode_metadata::get(&pool, asset.id)
        .await
        .unwrap()
        .expect("gcode_metadata row should exist");
    assert_eq!(meta.slicer_name.as_deref(), Some("OrcaSlicer"));
    assert!(meta.export_to_usb, "discovered gcode defaults to USB export");

    // Idempotent: a second sweep ingests nothing (relpath dedupe).
    let n2 = watcher::reconcile(&pool, &library).await.unwrap();
    assert_eq!(n2, 0, "re-running reconcile must not re-ingest tracked files");
}

#[tokio::test]
async fn reconcile_materializes_new_folder_and_object_from_disk() {
    let (_tmp, pool, library) = setup().await;

    // A brand-new tree dropped on disk — no folder/object rows exist for it yet.
    let dir = library.root().join("DIY Parts").join("Widget");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("widget_PLA_0.2_42m.gcode"), SAMPLE_GCODE).unwrap();
    std::fs::write(dir.join("widget.stl"), b"solid widget\nendsolid widget\n").unwrap();

    let n = watcher::reconcile(&pool, &library).await.unwrap();
    assert_eq!(n, 2, "both the gcode and the stl should be ingested");

    // The containing dir became an object under an auto-created "DIY Parts" folder.
    let folder = repository::folders::find_by_parent_and_dir(&pool, None, "DIY Parts")
        .await
        .unwrap()
        .expect("'DIY Parts' folder should be auto-created");
    let object = repository::objects::find_by_folder_and_dir(&pool, Some(folder.id), "Widget")
        .await
        .unwrap()
        .expect("'Widget' object should be auto-created");
    assert_eq!(object.name, "Widget");

    // Both files are tracked under that object.
    let gcode = repository::assets::find_by_relative_path(
        &pool,
        "DIY Parts/Widget/widget_PLA_0.2_42m.gcode",
    )
    .await
    .unwrap()
    .expect("gcode tracked");
    assert!(matches!(gcode.kind, AssetKind::Gcode));
    assert!(repository::assets::find_by_relative_path(&pool, "DIY Parts/Widget/widget.stl")
        .await
        .unwrap()
        .is_some());
}

#[tokio::test]
async fn reconcile_ignores_thumbnails_and_loose_root_files() {
    let (_tmp, pool, library) = setup().await;

    // A thumbnail (image in the reserved cache dir) and a loose file at the root
    // both lack a resolvable owning object → neither should be ingested.
    std::fs::write(
        library.root().join("thumbnails").join("abc.png"),
        b"\x89PNG\r\n",
    )
    .unwrap();
    std::fs::write(library.root().join("stray.gcode"), SAMPLE_GCODE).unwrap();

    let n = watcher::reconcile(&pool, &library).await.unwrap();
    assert_eq!(n, 0);
    assert!(
        repository::assets::find_by_relative_path(&pool, "stray.gcode")
            .await
            .unwrap()
            .is_none()
    );
}
