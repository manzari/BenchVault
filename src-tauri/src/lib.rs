#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let specta_builder = build_specta_builder();

    #[cfg(debug_assertions)]
    {
        let _ = specta_builder
            .export(
                specta_typescript::Typescript::default()
                    .bigint(specta_typescript::BigIntExportBehavior::Number)
                    .header("// @ts-nocheck\n// AUTO-GENERATED by tauri-specta. Do not edit by hand.\n"),
                "../src/lib/bindings.ts",
            )
            .ok();
    }

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_fs::init())
        .invoke_handler(specta_builder.invoke_handler())
        .setup(move |app| {
            specta_builder.mount_events(app);

            let handle = app.handle().clone();
            tauri::async_runtime::block_on(async move {
                let app_data = handle
                    .path()
                    .app_data_dir()
                    .expect("failed to resolve app_data_dir");
                std::fs::create_dir_all(&app_data).expect("failed to create app data dir");

                let library = Arc::new(library::Library::new(app_data.clone()));
                library.ensure_dirs().expect("library dirs");

                let db_path = app_data.join("benchvault.db");
                let pool = db::init_pool(&db_path).await.expect("init db");
                db::run_migrations(&pool).await.expect("run migrations");

                if let Err(e) = service::migrate_layout::run(&pool, &library).await {
                    eprintln!("[migrate_layout] {e}");
                }

                // Sweep the library for files that exist on disk but aren't tracked
                // yet (e.g. gcode a slicer saved into an object's folder while the app
                // was closed). Runs before the watcher spawns so the two never race.
                if let Err(e) = jobs::watcher::reconcile(&pool, &library).await {
                    eprintln!("[watcher] startup reconcile failed: {e}");
                }

                let watcher_pool = pool.clone();
                let watcher_library = Arc::clone(&library);
                let watcher_handle = handle.clone();

                // Populate mesh geometry for STLs added before mesh extraction
                // existed. Detached so it never delays startup; idempotent, so
                // later launches with nothing missing just run one cheap query.
                let backfill_pool = pool.clone();
                let backfill_library = Arc::clone(&library);
                tauri::async_runtime::spawn(async move {
                    match service::files::backfill_mesh_metadata(&backfill_pool, &backfill_library).await {
                        Ok(0) => {}
                        Ok(n) => eprintln!("[mesh] backfilled geometry for {n} STL(s)"),
                        Err(e) => eprintln!("[mesh] backfill failed: {e}"),
                    }
                    match service::files::backfill_threemf(&backfill_pool, &backfill_library).await {
                        Ok(0) => {}
                        Ok(n) => eprintln!("[3mf] backfilled geometry/metadata for {n} file(s)"),
                        Err(e) => eprintln!("[3mf] backfill failed: {e}"),
                    }
                    match service::files::backfill_scad_metadata(&backfill_pool, &backfill_library).await {
                        Ok(0) => {}
                        Ok(n) => eprintln!("[scad] backfilled metadata for {n} source(s)"),
                        Err(e) => eprintln!("[scad] backfill failed: {e}"),
                    }
                    match service::files::backfill_scad_geometry(&backfill_pool, &backfill_library).await {
                        Ok(0) => {}
                        Ok(n) => eprintln!("[scad] backfilled geometry for {n} source(s)"),
                        Err(e) => eprintln!("[scad] geometry backfill failed: {e}"),
                    }
                });

                let usb_sync_lock = Arc::new(tokio::sync::Mutex::new(()));
                let autosync = jobs::autosync::spawn(
                    handle.clone(),
                    pool.clone(),
                    Arc::clone(&library),
                    Arc::clone(&usb_sync_lock),
                );

                handle.manage(AppState {
                    db: pool,
                    library,
                    usb_sync_lock,
                    scad_render_lock: Arc::new(tokio::sync::Mutex::new(())),
                    autosync: autosync.clone(),
                });

                jobs::watcher::spawn(watcher_pool, watcher_library, watcher_handle, autosync);
            });

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
