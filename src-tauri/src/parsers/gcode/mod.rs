use std::fs::File;
use std::io::{Read, Seek, SeekFrom};
use std::path::Path;

use crate::domain::ParsedGcode;

const SNIFF_BYTES: usize = 64 * 1024;

#[derive(Debug, Clone, Copy)]
enum Slicer {
    PrusaFamily, // PrusaSlicer / SuperSlicer / OrcaSlicer / BambuStudio
    Cura,
    Unknown,
}

pub fn parse_path(path: &Path) -> std::io::Result<ParsedGcode> {
    let mut f = File::open(path)?;
    let head = read_chunk(&mut f, 0, SNIFF_BYTES)?;
    let len = f.metadata()?.len();
    let tail_offset = len.saturating_sub(SNIFF_BYTES as u64);
    let tail = if tail_offset > 0 {
        read_chunk(&mut f, tail_offset, SNIFF_BYTES)?
    } else {
        Vec::new()
    };

    let mut blob = String::with_capacity(head.len() + tail.len());
    blob.push_str(&String::from_utf8_lossy(&head));
    blob.push('\n');
    blob.push_str(&String::from_utf8_lossy(&tail));

    let slicer = detect(&blob);
    let mut parsed = match slicer {
        Slicer::PrusaFamily => prusa_family::parse(&blob),
        Slicer::Cura => cura::parse(&blob),
        Slicer::Unknown => ParsedGcode::default(),
    };

    if parsed.slicer_name.is_none() {
        parsed.slicer_name = match slicer {
            Slicer::PrusaFamily => Some("PrusaFamily".into()),
            Slicer::Cura => Some("Cura".into()),
            Slicer::Unknown => None,
        };
    }
    Ok(parsed)
}

fn read_chunk(f: &mut File, offset: u64, len: usize) -> std::io::Result<Vec<u8>> {
    f.seek(SeekFrom::Start(offset))?;
    // A single read() may return fewer bytes than requested; loop until the
    // buffer is full or EOF, so the tail sniff (where the Prusa family writes
    // all its settings) isn't silently truncated.
    let mut buf = Vec::with_capacity(len);
    f.take(len as u64).read_to_end(&mut buf)?;
    Ok(buf)
}

/// Remove OrcaSlicer 2.3.2's `; filament_colour_type = ...` comment lines, which
/// break Anycubic Kobra firmware's gcode parsing
/// (see https://github.com/OrcaSlicer/OrcaSlicer/issues/12444).
///
/// Operates on raw bytes so line endings (LF/CRLF) and any trailing-newline
/// quirks of the rest of the file are preserved untouched — only the offending
/// lines are dropped. Returns `Some(cleaned)` when at least one line was removed,
/// or `None` when the input was already clean (so callers can skip rewriting).
pub fn strip_kobra_breakers(input: &[u8]) -> Option<Vec<u8>> {
    let mut out: Vec<u8> = Vec::with_capacity(input.len());
    let mut removed = false;
    let mut idx = 0;
    while idx < input.len() {
        let end = match input[idx..].iter().position(|&b| b == b'\n') {
            Some(p) => idx + p + 1, // include the newline
            None => input.len(),
        };
        let line = &input[idx..end];
        if is_kobra_breaker_line(line) {
            removed = true;
        } else {
            out.extend_from_slice(line);
        }
        idx = end;
    }
    if removed {
        Some(out)
    } else {
        None
    }
}

/// Matches the bash reference regex `^[[:space:]]*;[[:space:]]*filament_colour_type[[:space:]]*=`
/// against a single line (which may carry a trailing CR/LF).
fn is_kobra_breaker_line(line: &[u8]) -> bool {
    const KEY: &[u8] = b"filament_colour_type";
    let mut i = 0;
    let skip_ws = |i: &mut usize| {
        while *i < line.len() && (line[*i] == b' ' || line[*i] == b'\t') {
            *i += 1;
        }
    };
    skip_ws(&mut i);
    if i >= line.len() || line[i] != b';' {
        return false;
    }
    i += 1;
    skip_ws(&mut i);
    if line.len() < i + KEY.len() || &line[i..i + KEY.len()] != KEY {
        return false;
    }
    i += KEY.len();
    skip_ws(&mut i);
    i < line.len() && line[i] == b'='
}

fn detect(blob: &str) -> Slicer {
    if blob.contains("PrusaSlicer")
        || blob.contains("SuperSlicer")
        || blob.contains("OrcaSlicer")
        || blob.contains("BambuStudio")
        || blob.contains("Bambu Studio")
    {
        Slicer::PrusaFamily
    } else if blob.contains("Cura_SteamEngine") || blob.contains("Cura_Steam") || blob.contains(";Generated with Cura") {
        Slicer::Cura
    } else {
        Slicer::Unknown
    }
}

#[cfg(test)]
mod kobra_tests {
    use super::strip_kobra_breakers;

    #[test]
    fn removes_the_offending_line() {
        let input = b"; generated by OrcaSlicer\n; filament_colour_type = 1;1;1;1\nG1 X0\n";
        let out = strip_kobra_breakers(input).expect("should remove a line");
        assert_eq!(out, b"; generated by OrcaSlicer\nG1 X0\n");
    }

    #[test]
    fn tolerates_whitespace_and_crlf() {
        let input = b"G1 X0\r\n  ;  filament_colour_type=1;1\r\nG1 X1\r\n";
        let out = strip_kobra_breakers(input).expect("should remove a line");
        assert_eq!(out, b"G1 X0\r\nG1 X1\r\n");
    }

    #[test]
    fn removes_final_line_without_trailing_newline() {
        let input = b"G1 X0\n; filament_colour_type = 1";
        let out = strip_kobra_breakers(input).expect("should remove a line");
        assert_eq!(out, b"G1 X0\n");
    }

    #[test]
    fn clean_file_returns_none() {
        let input = b"; filament_type = PLA\nG1 X0\n";
        assert!(strip_kobra_breakers(input).is_none());
    }

    #[test]
    fn does_not_match_substring_in_other_keys() {
        // A different key that merely contains the substring must be preserved.
        let input = b"; my_filament_colour_type_note = keep\n";
        assert!(strip_kobra_breakers(input).is_none());
    }
}
