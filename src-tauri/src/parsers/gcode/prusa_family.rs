// PrusaSlicer / SuperSlicer / OrcaSlicer / BambuStudio share most metadata comments.
use once_cell::sync::Lazy;
use regex::Regex;

use crate::domain::ParsedGcode;
use super::common::{capture_first, parse_duration_to_seconds, parse_sum_csv};

static GENERATED_BY: Lazy<Regex> = Lazy::new(|| {
    Regex::new(r"(?im)^;\s*generated by\s+(PrusaSlicer|SuperSlicer|OrcaSlicer|BambuStudio|Bambu Studio)\s*([\d\.\-A-Za-z]+)?").unwrap()
});
static EST_TIME_NORMAL: Lazy<Regex> =
    Lazy::new(|| Regex::new(r"(?im)^;\s*estimated printing time\s*\(normal mode\)\s*=\s*(.+)$").unwrap());
static EST_TIME_GENERIC: Lazy<Regex> =
    Lazy::new(|| Regex::new(r"(?im)^;\s*estimated printing time\s*=\s*(.+)$").unwrap());
static FILAMENT_LEN_MM: Lazy<Regex> =
    Lazy::new(|| Regex::new(r"(?im)^;\s*filament used\s*\[mm\]\s*=\s*(.+)$").unwrap());
static FILAMENT_WEIGHT_G: Lazy<Regex> =
    Lazy::new(|| Regex::new(r"(?im)^;\s*filament used\s*\[g\]\s*=\s*(.+)$").unwrap());
static FILAMENT_TYPE: Lazy<Regex> =
    Lazy::new(|| Regex::new(r"(?im)^;\s*filament_type\s*=\s*(.+)$").unwrap());
static LAYER_HEIGHT: Lazy<Regex> =
    Lazy::new(|| Regex::new(r"(?im)^;\s*layer_height\s*=\s*([\d\.]+)").unwrap());
static NOZZLE_TEMP: Lazy<Regex> = Lazy::new(|| {
    Regex::new(r"(?im)^;\s*(?:temperature|first_layer_temperature|nozzle_temperature)\s*=\s*([\d]+)")
        .unwrap()
});
static BED_TEMP: Lazy<Regex> = Lazy::new(|| {
    Regex::new(r"(?im)^;\s*(?:bed_temperature|first_layer_bed_temperature|hot_plate_temp)\s*=\s*([\d]+)")
        .unwrap()
});
static PROFILE_NAME: Lazy<Regex> = Lazy::new(|| {
    Regex::new(r"(?im)^;\s*(?:print_settings_id|setting_id|printer_settings_id)\s*=\s*(.+)$").unwrap()
});

pub fn parse(blob: &str) -> ParsedGcode {
    let mut p = ParsedGcode::default();

    if let Some(cap) = GENERATED_BY.captures(blob) {
        p.slicer_name = cap.get(1).map(|m| m.as_str().to_string());
        p.slicer_version = cap.get(2).map(|m| m.as_str().to_string()).filter(|s| !s.is_empty());
    }
    p.estimated_time_seconds = capture_first(&EST_TIME_NORMAL, blob)
        .or_else(|| capture_first(&EST_TIME_GENERIC, blob))
        .and_then(|s| parse_duration_to_seconds(&s));

    p.filament_length_mm = capture_first(&FILAMENT_LEN_MM, blob)
        .and_then(|s| parse_sum_csv(&s));
    p.filament_weight_g = capture_first(&FILAMENT_WEIGHT_G, blob)
        .and_then(|s| parse_sum_csv(&s));
    p.filament_type = capture_first(&FILAMENT_TYPE, blob);
    p.layer_height_mm = capture_first(&LAYER_HEIGHT, blob).and_then(|s| s.parse::<f64>().ok());
    p.nozzle_temp_c = capture_first(&NOZZLE_TEMP, blob).and_then(|s| s.parse::<i64>().ok());
    p.bed_temp_c = capture_first(&BED_TEMP, blob).and_then(|s| s.parse::<i64>().ok());
    p.profile_name = capture_first(&PROFILE_NAME, blob);

    p
}
